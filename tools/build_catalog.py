"""Validate every deck in content/decks/** and bundle them into app/assets/content/catalog.json.

    python tools/build_catalog.py            # validate + write the catalogue
    python tools/build_catalog.py --print    # also print every card (front | back) for review
    python tools/build_catalog.py --check    # validate only: nothing is written (safe to run in parallel)

Decks are grouped by origin: content/decks/originals (hand-written), content/decks/haiku and
content/decks/visual (written by Claude Haiku, reviewed). Picture decks (visual/) keep their images in
app/assets/content/img/<deck-id>/; this script checks every one exists, measures it so the app can lay
it out, and lists the image folders in pubspec.yaml. Problems that would break the app stop the build;
style issues are listed as warnings.
"""
import json
import pathlib
import re
import sys

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "content" / "decks"
OUT = ROOT / "app" / "assets" / "content" / "catalog.json"
IMG = ROOT / "app" / "assets" / "content" / "img"
PUBSPEC = ROOT / "app" / "pubspec.yaml"

CATEGORIES = {"lang": "Languages", "code": "Coding", "med": "Medicine", "science": "Science", "knowledge": "Knowledge"}
ORDER = ["lang", "code", "med", "science", "knowledge"]
TEMPLATES = {"text", "above", "below", "full", "only"}
FITS = {"cover", "contain"}


def check_images(deck: dict, where: str, errors: list, warnings: list) -> None:
    """Picture decks: every card's image must exist; measure it so the app can lay it out."""
    style = deck.get("style") or {}
    if style.get("front", "text") not in TEMPLATES:
        errors.append(f"{where}: style.front must be one of {sorted(TEMPLATES)}")
    if style.get("back", "text") not in TEMPLATES:
        errors.append(f"{where}: style.back must be one of {sorted(TEMPLATES)}")
    if style.get("fit", "cover") not in FITS:
        errors.append(f"{where}: style.fit must be one of {sorted(FITS)}")
    folder = IMG / deck["id"]
    used = set()
    for i, c in enumerate(deck["cards"]):
        for key in ("img", "bimg"):
            name = (c.get(key) or "").strip()
            if not name:
                continue
            f = folder / name
            if not f.is_file():
                errors.append(f"{where}: card {i} ({c.get('back')!r}) {key} {name!r} is not in {folder.relative_to(ROOT).as_posix()}")
                continue
            try:
                with Image.open(f) as im:
                    c["a" if key == "img" else "ba"] = round(im.width / im.height, 4)
                    if im.mode in ("RGBA", "LA") and im.getchannel("A").getextrema()[0] < 250:
                        c["al" if key == "img" else "bal"] = 1
            except Exception as e:  # noqa: BLE001
                errors.append(f"{where}: card {i} {key} {name!r} is unreadable ({e})")
            if name in used:
                errors.append(f"{where}: image {name!r} is used by two cards")
            used.add(name)
    on_disk = {f.name for f in folder.iterdir()} if folder.is_dir() else set()
    for extra in sorted(on_disk - used):
        warnings.append(f"{where}: image {extra!r} is in the folder but no card uses it")
    if not used:
        errors.append(f"{where}: a picture deck needs at least one image")


def sync_pubspec(image_decks: list) -> None:
    """Flutter bundles asset folders one by one; keep the generated block in pubspec.yaml current."""
    text = PUBSPEC.read_text(encoding="utf-8")
    block = (
        "    # picture decks (generated by tools/build_catalog.py)\n"
        + "".join(f"    - assets/content/img/{d}/\n" for d in sorted(image_decks))
        + "    # end picture decks\n"
    )
    pattern = re.compile(r"    # picture decks \(generated.*?    # end picture decks\n", re.S)
    if pattern.search(text):
        text = pattern.sub(lambda _: block, text)
    else:
        text = text.replace("    - assets/textures/\n", "    - assets/textures/\n" + block, 1)
    PUBSPEC.write_text(text, encoding="utf-8")


def check(deck: dict, path: pathlib.Path, errors: list, warnings: list) -> None:
    where = path.relative_to(ROOT).as_posix()
    for key in ("id", "name", "category", "cards"):
        if key not in deck:
            errors.append(f"{where}: missing {key}")
            return
    if deck["id"] != path.stem:
        errors.append(f"{where}: id {deck['id']!r} does not match the filename")
    if deck["category"] not in CATEGORIES:
        errors.append(f"{where}: unknown category {deck['category']!r}")
    if len(deck["name"]) > 28:
        warnings.append(f"{where}: name longer than 28 characters")
    if not deck["cards"]:
        errors.append(f"{where}: no cards")
    seen = set()
    for i, c in enumerate(deck["cards"]):
        front, back = (c.get("front") or "").strip(), (c.get("back") or "").strip()
        pictured = bool((c.get("img") or "").strip())
        if (not front and not pictured) or not back:
            errors.append(f"{where}: card {i} has an empty side")
        key = front or back
        if key in seen:
            errors.append(f"{where}: duplicate card {key!r}")
        seen.add(key)
        if len(front) > 70 or len(back) > 70:
            warnings.append(f"{where}: long side on card {i}: {front[:30]!r}")
        ex = (c.get("example") or "").strip()
        if ex and back and back.lower() in ex.lower() and deck["category"] != "lang":
            warnings.append(f"{where}: example may give away the answer on {front or back!r}")


def main() -> None:
    printing = "--print" in sys.argv
    check_only = "--check" in sys.argv
    errors, warnings, decks = [], [], []
    ids = set()
    for path in sorted(SRC.rglob("*.json")):
        deck = json.loads(path.read_text(encoding="utf-8"))
        origin = path.parent.name
        deck["origin"] = "haiku" if origin in ("haiku", "visual") else "originals"
        deck.setdefault("folder", CATEGORIES.get(deck.get("category"), "Library"))
        deck.setdefault("lang", None)
        deck.setdefault("kind", "text")
        deck.setdefault("level", "")
        deck.setdefault("description", "")
        check(deck, path, errors, warnings)
        if origin == "visual" and "cards" in deck and "id" in deck:
            check_images(deck, path.relative_to(ROOT).as_posix(), errors, warnings)
        if deck["id"] in ids:
            errors.append(f"{path.name}: duplicate deck id {deck['id']!r}")
        ids.add(deck["id"])
        for c in deck["cards"]:
            for k in ("label", "example", "hook"):
                c[k] = (c.get(k) or "").strip()
            c["front"] = (c.get("front") or "").strip()
            c["back"] = c["back"].strip()
        decks.append(deck)
        if printing:
            print(f"\n## {deck['id']} · {deck['name']} [{deck['category']}, {deck.get('lang')}] {len(deck['cards'])} cards")
            for c in deck["cards"]:
                extra = f"  ({c['label']})" if c["label"] else ""
                print(f"  {c['front'] or '[' + c.get('img', '') + ']'} | {c['back']}{extra}")

    decks.sort(key=lambda d: (ORDER.index(d["category"]) if d["category"] in ORDER else 99, d["origin"] != "originals", d["name"]))
    for w in warnings:
        print("warning:", w)
    if errors:
        for e in errors:
            print("ERROR:", e)
        raise SystemExit(1)
    pictured = sum(1 for d in decks for c in d["cards"] if c.get("img") or c.get("bimg"))
    if check_only:
        total = sum(len(d["cards"]) for d in decks)
        print(f"\ncheck passed: {len(decks)} decks, {total} cards, {pictured} with pictures (nothing written)")
        return
    sync_pubspec([d["id"] for d in decks if (IMG / d["id"]).is_dir()])
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps({"v": 2, "decks": decks}, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    total = sum(len(d["cards"]) for d in decks)
    by_origin = {}
    for d in decks:
        by_origin.setdefault(d["origin"], [0, 0])
        by_origin[d["origin"]][0] += 1
        by_origin[d["origin"]][1] += len(d["cards"])
    print(f"\n{len(decks)} decks, {total} cards ({pictured} with pictures) -> {OUT.relative_to(ROOT).as_posix()}")
    for k, (n, c) in by_origin.items():
        print(f"  {k}: {n} decks, {c} cards")


if __name__ == "__main__":
    main()
