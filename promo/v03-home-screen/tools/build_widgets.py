"""Copies the widget renders Video 3 uses out of a debug dump and writes assets/widgets.js, the manifest the
scenes read: each widget's size (dp), face (colour, corner radius), drawing (a transparent PNG at 2.625 px per dp)
and moving pieces (kind, place in dp, colour).

    python promo/v03-home-screen/tools/build_widgets.py <dump dir>

<dump dir> is the folder pulled from the emulator (adb pull .../files/widget_dump), holding red/, blue/, green/,
each with one folder per widget class. The dump: DebugReceiver DUMP with `--ez pieces true` (app/android/.../debug).
Sample days (widgets/Samples.kt, widgets/Preview.kt): a = 12 of 20 done, b = goal met, d = the Quick card turned,
g = the membership card's back, h = one card answered on the Quick card (13 of 20).
"""
import json
import pathlib
import shutil
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
DUMP = pathlib.Path(sys.argv[1])
OUT = ROOT / "assets" / "widgets"

PAGE1 = [("StreakWidget", "4×1"), ("SealWidget", "2×2"), ("ActionsGridWidget", "2×2"), ("TodayWidget", "4×2")]
NEEDS = []
for cls, size in PAGE1:
    NEEDS += [(cls, size, day, "red", "day") for day in "ahb"]
    NEEDS += [(cls, size, "b", acc, "day") for acc in ("blue", "green")]
    NEEDS += [(cls, size, "b", "green", "night")]
NEEDS += [("QuickCardWidget", "4×2", day, "red", "day") for day in "adh"]
NEEDS += [("MembershipWidget", "4×2", day, "red", "day") for day in "ag"]
NEEDS += [("SealsWidget", "4×1", "a", "red", "day")]
for cls, size in [("ForecastWidget", "4×2"), ("ActivityWidget", "4×2"), ("CardOfDayWidget", "4×2"),
                  ("SealsWidget", "4×1"), ("DecksWidget", "4×2"), ("StreakTallWidget", "1×2")]:
    NEEDS.append((cls, size, "b", "red", "day"))

OUT.mkdir(parents=True, exist_ok=True)
manifest = {}
for cls, size, day, acc, theme in NEEDS:
    src = DUMP / acc / cls / f"{cls}_{size}_{day}{'_night' if theme == 'night' else ''}"
    key = f"{cls}_{size.replace('×', 'x')}_{day}_{acc}_{theme}"
    data = json.loads(src.with_suffix(".json").read_text(encoding="utf-8"))
    shutil.copy2(f"{src}_ink.png", OUT / f"{key}.png")
    manifest[key] = {"w": data["w"], "h": data["h"], "face": data["face"],
                     "pieces": [{k: (round(v, 2) if isinstance(v, float) else v) for k, v in p.items()} for p in data["pieces"]],
                     "ink": f"assets/widgets/{key}.png"}

js = ("// Generated by tools/build_widgets.py from the app's widget dump: never edit by hand.\n"
      "window.MC_WIDGETS = " + json.dumps(manifest, indent=1) + ";\n")
(ROOT / "assets" / "widgets.js").write_text(js, encoding="utf-8")
print(f"{len(manifest)} widget renders -> {OUT.relative_to(ROOT)}")
