"""Writes Video 3's index.html: the scenes it mounts and the app's sounds, each placed one frame after the picture
that causes it, from the beats in SPEC.md (108 BPM).

    python promo/v03-home-screen/tools/build_root.py

Retime here (and in the scenes), then run it again; never hand-edit index.html.
"""
import pathlib
import wave

ROOT = pathlib.Path(__file__).resolve().parents[1]
FRAME = 1 / 30
DURATION = 32.0


def B(n):
    return n * 60 / 108


def length(name):
    with wave.open(str(ROOT / "assets" / "sounds" / f"{name}.wav")) as w:
        return w.getnframes() / w.getframerate()


S = []  # (id, sound, start s, volume)
S.append(("sx-hand", "whoosh", 0.2, 0.6))
for k, beat in enumerate((3, 4, 5, 6)):
    S.append((f"sx-land{k}", "card", B(beat) + FRAME, 0.9))
for k, beat in enumerate((12, 21, 28, 34)):
    S.append((f"sx-page{k}", "whoosh", B(beat) + 0.05, 0.45))
S.append(("sx-reveal", "flip", B(15) + FRAME, 0.85))
S.append(("sx-gotit", "good", B(18) + FRAME, 0.8))
n0, n1 = B(23), B(25.5)
for k in range(1, 7):
    S.append((f"sx-count{k}", "soft", n0 + (k / 6) * (n1 - n0) + FRAME, 0.55))
S.append(("sx-stamp", "stamp", B(26) + FRAME, 0.62))
S.append(("sx-fanfare", "fanfare", B(26) + 0.2, 0.7))
S.append(("sx-swap1", "card", B(29.5) + 0.07 + FRAME, 0.9))
S.append(("sx-swap2", "card", B(32) + 0.07 + FRAME, 0.9))
S.append(("sx-settings", "whoosh", B(34.4), 0.5))
for k, beat in enumerate((36, 38, 40, 42)):
    S.append((f"sx-tap{k}", "soft", B(beat) + FRAME, 0.7))
    for i in range(4):
        S.append((f"sx-wave{k}{i}", "tick", B(beat) + 0.15 + i * 0.06 + FRAME, 0.45))
S.append(("sx-dive", "whoosh", B(43.5), 0.4))
for k in range(7):
    S.append((f"sx-cut{k}", ("card", "pop")[k % 2], B(44 + k) + FRAME, 0.75))
S.append(("sx-wipe", "whoosh", B(51) + 0.002, 0.8))
for k, beat in enumerate((52, 52.5, 53)):
    S.append((f"sx-deal{k + 1}", "card", B(beat) + FRAME, 0.9))

lanes, audio = [], ['      <audio id="music" src="assets/sounds/music.wav" data-start="0" data-duration="32.000" data-track-index="10" data-volume="1.5"></audio>']
for aid, name, t, vol in sorted(S, key=lambda s: s[2]):
    d = min(round(length(name) + 0.005, 3), round(DURATION - t, 3))
    lane = next((i for i, end in enumerate(lanes) if end <= t), len(lanes))
    lanes[lane:lane + 1] = [t + d]
    audio.append(f'      <audio id="{aid}" src="assets/sounds/{name}.wav" data-start="{t:.3f}" data-duration="{d:.3f}" data-track-index="{11 + lane}" data-volume="{vol}"></audio>')

home_end = round(B(44) + 0.1, 4)
mont = round(B(44), 4)
end0 = round(B(51), 4)
nl = "\n"
html = f'''<!doctype html>
<!-- Generated by tools/build_root.py: edit that, then run it again. -->
<html lang="en" data-resolution="portrait">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1080, height=1920" />
    <title>Memory Card · Video 3 · Your home screen remembers too</title>
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/CustomEase.min.js"></script>
    <script src="assets/widgets.js"></script>
    <script src="assets/wgkit.js"></script>
    <style>
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ margin: 0; width: 1080px; height: 1920px; overflow: hidden; background: #EAEAEA; }}
      #root {{ position: relative; width: 100%; height: 100%; }}
      /* A faint paper grain over the whole frame (the brief: 2-3 %). */
      #grain {{ position: absolute; inset: 0; z-index: 50; pointer-events: none; background-image: url("assets/textures/grain_fine.png"); background-size: 256px 256px; opacity: 0.12; mix-blend-mode: multiply; }}
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="{DURATION}" data-width="1080" data-height="1920">
      <div id="home" data-composition-id="home" data-composition-src="compositions/home.html"
        data-start="0" data-duration="{home_end}" data-track-index="1" data-track-kind="graphics" data-width="1080" data-height="1920" style="z-index:1"></div>
      <div id="montage" data-composition-id="montage" data-composition-src="compositions/montage.html"
        data-start="{mont}" data-duration="{round(end0 + 0.6 - mont, 4)}" data-track-index="2" data-track-kind="graphics" data-width="1080" data-height="1920" style="z-index:2"></div>
      <div id="titles" data-composition-id="titles" data-composition-src="compositions/titles.html"
        data-start="0" data-duration="{round(end0 + 0.6, 4)}" data-track-index="3" data-track-kind="graphics" data-width="1080" data-height="1920" style="z-index:3"></div>
      <div id="endcard" data-composition-id="endcard" data-composition-src="compositions/endcard.html"
        data-start="{end0}" data-duration="{round(DURATION - end0, 4)}" data-track-index="4" data-track-kind="graphics" data-width="1080" data-height="1920" style="z-index:4"></div>
      <div id="grain"></div>

      <!-- Music bed: 108 BPM, made with the app's synth (tools/make_music.py). Swap the file to change it. -->
      <!-- The app's own sounds (app/assets/sounds), each one frame after the picture that causes it. -->
{nl.join(audio)}
    </div>
    <script>
      window.__timelines = window.__timelines || {{}};
      window.__timelines["main"] = gsap.timeline({{ paused: true }});
    </script>
  </body>
</html>
'''
(ROOT / "index.html").write_text(html, encoding="utf-8")
print(f"index.html: {len(S)} sounds on {len(lanes)} lanes")
